// docs/v1/contract.md: defineContract / defineScope / defineApi / ApiTypes and the derived errors (C4b #228).
// One file stands in for a folder tree; the comments name the files it would be.
import { expectTypeOf } from 'vitest'
import * as z from 'zod'
import { apiEndpoint, apiRoutes, defineApi, defineContract, defineError, defineScope, endpoint } from '@laratype/contract'
import type { ApiRouteName, ApiTypes, ContractPrefix } from '@laratype/contract'

const UserDto = z.object({ id: z.number(), name: z.string(), email: z.string().email() })
const PostDto = z.object({ id: z.number(), title: z.string() })

// app/api/_errors.ts: domain errors, FE-importable. The "_" keeps it out of the contract tree.
export const EmailTaken = defineError(409, 'EMAIL_TAKEN', (email: string) => ({ message: 'The email is taken.', email }))

// app/api/users.ts → /api/users. A root-level folder has no Prefix to import.
export const users = defineContract()({
  index: endpoint.get('/').query(z.object({ page: z.coerce.number().default(1) })).response(z.array(UserDto)), // 401, 422
  show: endpoint.get('/:user').response(UserDto),                                                              // 401, 404
  store: endpoint.post('/').body(z.object({ name: z.string().min(1), email: z.string().email() })).response(UserDto, 201).throws(EmailTaken), // 401, 422, EMAIL_TAKEN
  stats: endpoint.get('/stats').public(),                                                                       // none
}, { auth: true })

// .laratype/types/app/api/users/[user]/$types.d.ts (generated by G1 #133):
//   export type Prefix = ContractPrefix<'/api/users/:user', [typeof import('./_scope').default]>
//   export type ScopePrefix = ContractPrefix<'/api/users/:user', []>
type ScopePrefix = ContractPrefix<'/api/users/:user', []>

// app/api/users/[user]/_scope.ts: every contract below gets 401 and 403.
export const usersUser = defineScope<ScopePrefix>()({ auth: true, authorize: true })
type Prefix = ContractPrefix<'/api/users/:user', [typeof usersUser]>

// app/api/users/[user]/posts.ts → /api/users/:user/posts
export const posts = defineContract<Prefix>()({
  index: endpoint.get('/').response(z.array(PostDto)).authorize(false), // 401, 404 ([user] folder)
  update: endpoint.patch('/:post').body(PostDto.pick({ title: true })).throttle({ limit: 10, per: '1m' }), // 401, 403, 404, 422, 429
})

// .laratype/api/index.gen.ts (generated by G1 #133): the only module a FE imports, as `$api`.
export const appApi = defineApi({
  users: { contract: users, path: '/api/users', scopes: [] },
  'users.posts': { contract: posts, path: '/api/users/:user/posts', scopes: [{ scope: usersUser, dir: 'users/[user]' }] },
})
export type AppApi = typeof appApi

// Route names are the folder names plus the endpoint key.
expectTypeOf<ApiRouteName<AppApi>>().toEqualTypeOf<
  'users.index' | 'users.show' | 'users.store' | 'users.stats' | 'users.posts.index' | 'users.posts.update'
>()
expectTypeOf(apiEndpoint(appApi, 'users.posts.update')).toEqualTypeOf<typeof posts.update>()
expectTypeOf(appApi.users.posts.update).toEqualTypeOf<typeof posts.update>()
// Each route: full path, resolved auth/authorize/throttle and its errors.
export const routes = apiRoutes(appApi).map(({ name, path, errors }) => [name, path, errors.map((e) => e.code)])

// Schema-free projection for the client and `sauf types:generate`: full paths, folder params, derived errors.
type Api = ApiTypes<AppApi>
expectTypeOf<Api['users']['index']['query']>().toEqualTypeOf<{ page?: number | undefined }>()
expectTypeOf<Api['users']['posts']['update']['path']>().toEqualTypeOf<'/api/users/:user/posts/:post'>()
expectTypeOf<Api['users']['posts']['update']['params']>().toEqualTypeOf<{ user: string; post: string }>()
expectTypeOf<Api['users']['store']['status']>().toEqualTypeOf<201>()
expectTypeOf<Api['users']['store']['errors']['code']>().toEqualTypeOf<'VALIDATION_ERROR' | 'UNAUTHORIZED' | 'EMAIL_TAKEN'>()
expectTypeOf<Api['users']['posts']['update']['errors']['status']>().toEqualTypeOf<401 | 403 | 404 | 422 | 429>()
expectTypeOf<Api['users']['stats']['errors']>().toEqualTypeOf<never>()

defineContract<Prefix>()({
  // @ts-expect-error .public() under a scope with authorize: add .authorize(false) or move the contract out of the scope
  feed: endpoint.get('/feed').public(),
})
