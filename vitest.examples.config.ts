import { fileURLToPath } from "node:url";
import { Compiler, type Options } from "@swc/core";
import type { Plugin } from "vite";
import { configDefaults, mergeConfig } from "vitest/config";
import { entries } from "./scripts/alias";
import config from "./vitest.config";
import { laratypeDi } from "./packages/sauf/src/di/plugin";

/**
 * `examples/basic`'s tests (E1 #111): they boot the real app, so their app code goes through the transform chain of
 * `sauf dev` (docs/v1/build.md › Plugin chain): the `laratype:di` transform that records constructor dependencies
 * (docs/v1/di.md › Vite plugin `laratype:di`), then SWC with `legacyDecorator` and `decoratorMetadata`, which the
 * TypeORM models need. The unit project runs esbuild and installs neither.
 *
 * The project root is the example, so `laratype:di` transforms `app/**` (app code) and skips the framework packages'
 * `src`, which is outside the root. `$types.d.ts` and `$api` are generated by `__tests__/support/generate.ts` first.
 */
const exampleDir = fileURLToPath(new URL("./examples/basic", import.meta.url));
const alias = {
  ...entries,
  // The contract tree generated by `sauf types:generate` (examples/basic/tsconfig.json's `$api`)
  $api: fileURLToPath(new URL("./examples/basic/.laratype/api/index.gen.ts", import.meta.url)),
};

const swcOptions: Options = {
  sourceMaps: true,
  module: { type: "es6" },
  jsc: {
    target: "es2022",
    parser: { syntax: "typescript", decorators: true, tsx: false },
    transform: { legacyDecorator: true, decoratorMetadata: true },
  },
};

/** `sauf dev`'s SWC step (packages/sauf/src/utils/plugin.ts), without its `@laratype/*` resolution. */
const swc = (): Plugin => {
  let compiler: Compiler | undefined;
  return {
    name: "examples:swc",
    enforce: "pre",
    async transform(code, id) {
      if (!/\.(?:ts|tsx|jsx)$/.test(id.replace(/[?#].*$/, ""))) return null;
      compiler ??= new Compiler();
      const result = await compiler.transform(code, { ...swcOptions, filename: id });
      return { code: result.code, map: result.map };
    },
  };
};

export default mergeConfig(config, {
  root: exampleDir,
  // esbuild would strip the decorators' metadata; SWC below emits it, as `sauf dev` does
  esbuild: false,
  plugins: [laratypeDi(), swc()],
  resolve: { alias },
  test: {
    name: "examples",
    root: exampleDir,
    alias,
    include: ["__tests__/**/*.test.ts"],
    exclude: [...configDefaults.exclude, "**/e2e/**"],
    globalSetup: [fileURLToPath(new URL("./examples/basic/__tests__/support/generate.ts", import.meta.url))],
    hookTimeout: 30_000,
  },
});
