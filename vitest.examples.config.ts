import { fileURLToPath } from "node:url";
import { Compiler, type Options } from "@swc/core";
import type { Plugin } from "vite";
import { configDefaults, mergeConfig } from "vitest/config";
import { entries } from "./scripts/alias";
import config from "./vitest.config";
import { laratypeManifest } from "./packages/sauf/src/manifest";
import { laratypeDi } from "./packages/sauf/src/di/plugin";

/**
 * `examples/basic`'s tests (E1 #111, E5 #343): they boot the real app, so their app code goes through the transform
 * chain of `sauf dev` (docs/v1/build.md › Plugin chain): `laratype:manifest` serves `virtual:laratype/app` (loaded by
 * `useAppManifest` in `__tests__/support/boot.ts`), the `laratype:di` transform records constructor dependencies
 * (docs/v1/di.md › Vite plugin `laratype:di`), then SWC with `legacyDecorator` and `decoratorMetadata`, which the
 * TypeORM models need. The unit project runs esbuild and installs none of them.
 *
 * The project root is the example, so `laratype:di` transforms `app/**` (app code) and skips the framework packages'
 * `src`, which is outside the root. `$types.d.ts` and `$api` are generated by `__tests__/support/generate.ts` first;
 * folding that scan and the SWC step into the shared plugin chain stays with B2 #126.
 */
const exampleDir = fileURLToPath(new URL("./examples/basic", import.meta.url));
const alias = {
  ...entries,
  // The contract tree generated by `sauf types:generate` (examples/basic/tsconfig.json's `$api`)
  $api: fileURLToPath(new URL("./examples/basic/.laratype/api/index.gen.ts", import.meta.url)),
};

const swcOptions: Options = {
  sourceMaps: true,
  module: { type: "es6" },
  jsc: {
    target: "es2022",
    // Set per file: `.tsx` needs `tsx: true`, while `.ts`, `.mts` and `.cts` keep angle-bracket assertions
    parser: { syntax: "typescript", decorators: true, tsx: false },
    transform: { legacyDecorator: true, decoratorMetadata: true },
  },
};

/** The TypeScript and JSX extensions SWC must transform: with esbuild off, `.mts`/`.cts` would reach Node untransformed. */
const scriptRE = /\.(?:[cm]?ts|[jt]sx)$/;
const tsxRE = /\.[jt]sx$/;

/** `sauf dev`'s SWC step (packages/sauf/src/utils/plugin.ts), without its `@laratype/*` resolution. */
const swc = (): Plugin => {
  let compiler: Compiler | undefined;
  return {
    name: "examples:swc",
    enforce: "pre",
    async transform(code, id) {
      const file = id.replace(/[?#].*$/, "");
      if (!scriptRE.test(file)) return null;
      compiler ??= new Compiler();
      const result = await compiler.transform(code, {
        ...swcOptions,
        filename: id,
        jsc: {
          ...swcOptions.jsc,
          parser: { syntax: "typescript", decorators: true, tsx: tsxRE.test(file) },
        },
      });
      return { code: result.code, map: result.map };
    },
  };
};

export default mergeConfig(config, {
  root: exampleDir,
  // esbuild would strip the decorators' metadata; SWC below emits it, as `sauf dev` does
  esbuild: false,
  // `virtual:laratype/app`: the app manifest of docs/v1/build.md › Plugin chain, scanned from the project folder
  plugins: [laratypeManifest({ projectDir: exampleDir }), laratypeDi(), swc()],
  resolve: { alias },
  test: {
    name: "examples",
    root: exampleDir,
    alias,
    include: ["__tests__/**/*.test.ts"],
    exclude: [...configDefaults.exclude, "**/e2e/**"],
    globalSetup: [fileURLToPath(new URL("./examples/basic/__tests__/support/generate.ts", import.meta.url))],
    hookTimeout: 30_000,
  },
});
