/**
 * `laratype:api`: resolves `$api` to the generated `<out>/api/index.gen.ts` (docs/v1/http.md › Router v2).
 * The first `$api` import scans the contract tree and writes its files, with the root and base from config
 * `api.root` / `api.base`. Once the app has imported `$api`, the type watch (`refresh()`, G2 #142) and `sauf dev`'s
 * `--hmr` restarts rescan when the tree can have changed (`affectsTree()`), so an app that never imports it is never
 * scanned. Production scans nothing: the build compiles the generated index (#125). No runtime import of vite: this
 * module is loaded on every `sauf` start.
 */
import { existsSync, readFileSync } from 'node:fs';
import { isAbsolute, join, relative, resolve } from 'node:path';
import type { Plugin, ViteDevServer } from 'vite';
import { DEFAULT_OUT, DEFAULT_ROOT, apiTreeConfig, readApiTreeConfig, resolveApiTree } from './config';
import type { ApiTreeConfig } from './config';
import { inModelsDir } from '../manifest/scan';
import { ScanError, isTreeFile } from './scan';
import { inside, slash, syncContractTree } from './sync';

export const API_PLUGIN_NAME = 'laratype:api';
export const API_ALIAS = '$api';

export interface ApiPluginOptions {
  /** Project directory. Default `process.cwd()`. */
  readonly projectDir?: string;
  /** Output folder, relative to the project. Default `.laratype`. */
  readonly outDir?: string;
  /** The config object. Default: `app/config/config.ts`, imported on its own, so a change to it applies on the next restart. */
  readonly config?: () => unknown;
}

/** `plugin.api` of `laratype:api`, used by `sauf dev`. */
export interface ApiPluginApi {
  /**
   * Scans the tree again and writes the files that changed. Serialized with every other scan (a call during a scan
   * queues exactly one follow-up). A rejected scan is not cached: the next call retries.
   */
  rescan(): Promise<void>;
  /**
   * The type watch's scan (G2 #142): rescans when the app has imported `$api` before, otherwise does nothing. Called
   * by `sauf dev` on every relevant watcher event, without a restart.
   */
  refresh(): Promise<void>;
  /** Called before each dev (re)start: rescans when the app has imported `$api` before, otherwise does nothing. */
  restart(): Promise<void>;
  /** Whether adding or deleting `file` changes the contract tree: it is under the root of the last scan (the default root until a config loaded). */
  inTree(file: string): boolean;
  /** Whether `file` is generated by the scan (under the output folder), so a write there must not restart the server. */
  isGenerated(file: string): boolean;
  /** Whether a watcher event can change the tree: a file added or deleted under the root, or any event on the config file. */
  affectsTree(event: "change" | "add" | "unlink", file: string): boolean;
}


export function laratypeApi(options: ApiPluginOptions = {}): Plugin<ApiPluginApi> {
  const projectDir = options.projectDir ?? process.cwd();
  const outDir = options.outDir ?? DEFAULT_OUT;
  const indexFile = join(projectDir, outDir, 'api', 'index.gen.ts');
  const indexId = slash(indexFile);
  const configFile = resolve(projectDir, 'app', 'config', 'config.ts');
  const outPath = resolve(projectDir, outDir);
  let lastScan: Promise<void> | undefined;
  let used = false;
  // The default root until a scan has read the config, so a first scan that fails still restarts on contract adds
  let rootPath = resolve(projectDir, DEFAULT_ROOT);
  let missingRoot: string | undefined;
  let server: ViteDevServer | undefined;

  // readApiTreeConfig imports the config outside Vite (jiti), so a config importing `$api` fails there, never re-enters here.
  // It evaluates the config's whole import graph (no module cache), so it runs again only when config.ts changed: a
  // rescan for a contract add or unlink reuses the last value. A failed read is not kept.
  let lastConfig: { source: string; value: ApiTreeConfig } | undefined;
  const loadConfig = async () => {
    if (options.config) return apiTreeConfig(options.config());
    const source = existsSync(configFile) ? readFileSync(configFile, 'utf8') : '';
    if (lastConfig?.source !== source) lastConfig = { source, value: await readApiTreeConfig(projectDir) };
    return lastConfig.value;
  };

  const scan = async () => {
    const tree = resolveApiTree({}, await loadConfig());
    rootPath = resolve(projectDir, tree.root);
    const result = syncContractTree({ projectDir, outDir, ...tree });
    missingRoot = result ? undefined : tree.root;
    // A rewritten index must not be served from the module cache, nor a stale one once the root is gone: invalidate
    // it and its importers (the module graph is keyed by normalized ids), so the next load reaches load() below
    if (server && (missingRoot !== undefined || result?.changed.length)) {
      for (const mod of server.moduleGraph.getModulesByFile(indexId) ?? []) {
        server.moduleGraph.invalidateModule(mod, new Set(), Date.now(), true);
      }
    }
  };

  // One scan at a time: the type watch, a restart and a first $api import can ask together, and a scan reads names
  // only, so the calls that arrive during one coalesce into exactly one follow-up instead of racing its writes.
  const scans = coalesce(scan);
  const rescan = () => {
    const run = scans.run().catch((error: unknown) => {
      // The original's cause (the jiti import error and its stack) is kept
      throw error instanceof ScanError ? new ScanError(`[${API_PLUGIN_NAME}] ${error.message}`, { cause: error.cause }) : error;
    });
    lastScan = run;
    // A rejected scan is not cached: the next import or watcher event retries
    void run.catch(() => {
      if (lastScan === run) lastScan = undefined;
    });
    return run;
  };

  const refresh = async () => {
    if (used) await rescan();
  };

  // A stale index.gen.ts would import contracts that may be gone
  const checkRoot = () => {
    if (missingRoot !== undefined) {
      throw new ScanError(`[${API_PLUGIN_NAME}] the app imports $api, but the contract tree root "${missingRoot}" does not exist (set config api.root)`);
    }
  };

  /** Whether `file` is a model module the type scan reads (H14 #163): adding or deleting one changes `models.d.ts`. */
  const inModels = (file: string) => {
    const rel = relative(projectDir, resolve(file));
    return !rel.startsWith('..') && !isAbsolute(rel) && inModelsDir(slash(rel));
  };

  const api: ApiPluginApi = {
    rescan,
    refresh,
    restart: refresh,
    // A contract or a _scope.ts the scan would read: not a private _x/$x folder, a non-.ts file or an editor temp file
    // The output folder is skipped like the scan does (it is inside the root with `api.root: '.'`)
    inTree: (file) =>
      used && inside(rootPath, resolve(file)) && !inside(outPath, resolve(file)) && isTreeFile(slash(relative(rootPath, resolve(file)))),
    isGenerated: (file) => inside(outPath, resolve(file)),
    // A model added or deleted (not edited: the generated file imports it) changes `models.d.ts` too (H14 #163)
    affectsTree: (event, file) => resolve(file) === configFile || (event !== 'change' && (api.inTree(file) || inModels(file))),
  };

  return {
    name: API_PLUGIN_NAME,
    enforce: 'pre',
    api,
    configureServer(devServer) {
      server = devServer;
    },
    async resolveId(source) {
      if (source !== API_ALIAS) return null;
      used = true;
      await (lastScan ?? rescan());
      checkRoot();
      return existsSync(indexFile) ? indexFile : null;
    },
    // A cached importer loads the index by its id without resolving `$api` again: check the root there too
    load(id) {
      if (slash(id.replace(/[?#].*$/, '')) === indexId) checkRoot();
      return null;
    },
  };
}

/** The `laratype:api` plugin API of a Vite server, if it has the plugin. */
export const contractTreePlugin = (plugins: readonly { name: string; api?: unknown }[]): ApiPluginApi | undefined =>
  plugins.find((p) => p.name === API_PLUGIN_NAME)?.api as ApiPluginApi | undefined;

/** One task at a time: calls during a run coalesce into exactly one follow-up run, never a concurrent one. */
export interface CoalescedTask {
  /** Runs now, or after the in-flight run. Resolves with the last queued run's outcome. */
  run(): Promise<void>;
}

/**
 * Serializes `task` and coalesces concurrent calls: while a run is in flight any number of `run()` calls queue exactly
 * one follow-up. The queue drains even when a run throws and the shared promise rejects only when the last run failed,
 * so a call that arrives during a failed run is not dropped and a failing scan, even one that throws synchronously, is
 * not cached.
 */
export function coalesce(task: () => Promise<void>): CoalescedTask {
  let running: Promise<void> | undefined;
  let requested = false;
  let settled = 0;
  const drain = async (): Promise<void> => {
    let failed = false;
    let failure: unknown;
    try {
      while (requested) {
        requested = false;
        failed = false;
        try {
          await task();
        } catch (error) {
          failed = true;
          failure = error;
        }
      }
      if (failed) throw failure;
    } finally {
      running = undefined;
      settled++;
    }
  };
  return {
    run() {
      requested = true;
      if (running) return running;
      const before = settled;
      const current = drain();
      // `drain` runs synchronously up to its first `await`, so a task that throws synchronously settles it (and clears
      // `running`) before this assignment. Storing that rejected promise would cache the failure and drop later calls.
      if (settled === before) running = current;
      return current;
    },
  };
}
