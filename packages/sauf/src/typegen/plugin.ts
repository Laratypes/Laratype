/**
 * `laratype:api`: resolves `$api` to the generated `<out>/api/index.gen.ts` (docs/v1/http.md › Router v2).
 * The first `$api` import scans the contract tree and writes its files, with the root and base from config
 * `api.root` / `api.base`. Once the app has imported `$api`, `sauf dev` rescans before a restart when the tree can
 * have changed (`affectsTree()`, then `restart()`), so an app that never imports it is never scanned. Production reads
 * the build manifest instead (#125). No runtime import of vite: this module is loaded on every `sauf` start.
 */
import { existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import type { Plugin, ViteDevServer } from 'vite';
import { apiTreeConfig, readApiTreeConfig, resolveApiTree } from './config';
import { ScanError } from './scan';
import { inside, slash, syncContractTree } from './sync';

export const API_PLUGIN_NAME = 'laratype:api';
export const API_ALIAS = '$api';

export interface ApiPluginOptions {
  /** Project directory. Default `process.cwd()`. */
  readonly projectDir?: string;
  /** Output folder, relative to the project. Default `.laratype`. */
  readonly outDir?: string;
  /** The config object. Default: `app/config/config.ts`, imported on its own, so a change to it applies on the next restart. */
  readonly config?: () => unknown;
}

/** `plugin.api` of `laratype:api`, used by `sauf dev`. */
export interface ApiPluginApi {
  /** Scans the tree again and writes the files that changed. A rejected scan is not cached: the next call retries. */
  rescan(): Promise<void>;
  /** Called before each dev (re)start: rescans when the app has imported `$api` before, otherwise does nothing. */
  restart(): Promise<void>;
  /** Whether adding or deleting `file` changes the contract tree (it is under the root of the last scan). */
  inTree(file: string): boolean;
  /** Whether `file` is generated by the scan (under the output folder), so a write there must not restart the server. */
  isGenerated(file: string): boolean;
  /** Whether a watcher event can change the tree: a file added or deleted under the root, or any event on the config file. */
  affectsTree(event: "change" | "add" | "unlink", file: string): boolean;
}


export function laratypeApi(options: ApiPluginOptions = {}): Plugin<ApiPluginApi> {
  const projectDir = options.projectDir ?? process.cwd();
  const outDir = options.outDir ?? '.laratype';
  const indexFile = join(projectDir, outDir, 'api', 'index.gen.ts');
  const indexId = slash(indexFile);
  const configFile = resolve(projectDir, 'app', 'config', 'config.ts');
  const outPath = resolve(projectDir, outDir);
  let current: Promise<void> | undefined;
  let used = false;
  let rootPath: string | undefined;
  let missingRoot: string | undefined;
  let server: ViteDevServer | undefined;

  const scan = async () => {
    const tree = resolveApiTree({}, options.config ? apiTreeConfig(options.config()) : await readApiTreeConfig(projectDir));
    rootPath = resolve(projectDir, tree.root);
    const result = syncContractTree({ projectDir, outDir, ...tree });
    missingRoot = result ? undefined : tree.root;
    // A rewritten index must not be served from the module cache, nor a stale one once the root is gone: invalidate
    // it and its importers (the module graph is keyed by normalized ids), so the next load reaches load() below
    if (server && (missingRoot !== undefined || result?.changed.length)) {
      for (const mod of server.moduleGraph.getModulesByFile(indexId) ?? []) {
        server.moduleGraph.invalidateModule(mod, new Set(), Date.now(), true);
      }
    }
  };

  const rescan = () => {
    const run = scan().catch((error: unknown) => {
      if (current === run) current = undefined;
      throw error instanceof ScanError ? new ScanError(`[${API_PLUGIN_NAME}] ${error.message}`) : error;
    });
    current = run;
    return run;
  };

  // A stale index.gen.ts would import contracts that may be gone
  const checkRoot = () => {
    if (missingRoot !== undefined) {
      throw new ScanError(`[${API_PLUGIN_NAME}] the app imports $api, but the contract tree root "${missingRoot}" does not exist (set config api.root)`);
    }
  };

  const api: ApiPluginApi = {
    rescan,
    restart: async () => {
      if (used) await rescan();
    },
    inTree: (file) => rootPath !== undefined && inside(rootPath, resolve(file)),
    isGenerated: (file) => inside(outPath, resolve(file)),
    affectsTree: (event, file) => resolve(file) === configFile || (event !== 'change' && api.inTree(file)),
  };

  return {
    name: API_PLUGIN_NAME,
    enforce: 'pre',
    api,
    configureServer(devServer) {
      server = devServer;
    },
    async resolveId(source) {
      if (source !== API_ALIAS) return null;
      used = true;
      await (current ?? rescan());
      checkRoot();
      return existsSync(indexFile) ? indexFile : null;
    },
    // A cached importer loads the index by its id without resolving `$api` again: check the root there too
    load(id) {
      if (slash(id.replace(/[?#].*$/, '')) === indexId) checkRoot();
      return null;
    },
  };
}

/** The `laratype:api` plugin API of a Vite server, if it has the plugin. */
export const contractTreePlugin = (plugins: readonly { name: string; api?: unknown }[]): ApiPluginApi | undefined =>
  plugins.find((p) => p.name === API_PLUGIN_NAME)?.api as ApiPluginApi | undefined;
