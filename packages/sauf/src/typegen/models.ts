import { posix } from "node:path";
import { camelize } from "@laratype/support";
import { ManifestScanError, scanModels } from "../manifest/scan";
import type { ScannedEntry } from "../manifest/scan";
import { lines, quote } from "./emit";
import type { GeneratedFile } from "./emit";
import { ScanError } from "./scan";

/**
 * `<out>/types/models.d.ts` (docs/v1/typegen.md › sauf types:generate, H14 #163): the app's implicit model bindings,
 * keyed by path param. One module augmentation of `@laratype/http`'s `Register`, so the route proof turns a registered
 * key into the model class (`Ctx<typeof users.show>` → `params.user: User`) without a `r.bind()`.
 *
 * The keys are `camelize(<manifest file name>)`, the same function on the same string the database provider uses at
 * boot, so the types and the runtime cannot disagree. Names only: a model module is never loaded (the typegen never
 * runs app code), so a file without a default export fails in the app's tsc and at the database boot, not here.
 */

/** The models file's name under `<out>/types/`. */
export const MODELS_FILE = "models.d.ts";

/** The options of {@link emitModelsFile}: the project whose manifest model folders are scanned, and the output folder. */
export interface ModelsFileOptions {
  /** Project directory (absolute). */
  readonly projectDir: string;
  /** Output folder, relative to the project: `.laratype`. */
  readonly outDir: string;
}

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/**
 * The model's module path in the generated import: `.ts` / `.js` stay extension-less (the project's tsc resolves them
 * like any app import), while `.mts` becomes `.mjs` and `.mjs` keeps its extension: TypeScript resolves an
 * extension-less import to neither `.mts` nor `.mjs` (H14 #420 CR).
 */
const modelSpecifier = (path: string) =>
  path.endsWith(".mts") ? `${path.slice(0, -".mts".length)}.mjs` : path.endsWith(".mjs") ? path : path.replace(/\.[cm]?[jt]s$/, "");

/** The keys of the app's models, checked and sorted: `{ key, path }`, with `__proto__` and collisions refused. */
export function modelKeys(entries: readonly ScannedEntry[]): { readonly key: string; readonly path: string }[] {
  const byKey = new Map<string, string>();
  const out: { key: string; path: string }[] = [];
  for (const entry of entries) {
    const key = camelize(entry.name);
    if (key === "__proto__") {
      throw new ScanError(
        `${JSON.stringify(entry.path)}: a model file cannot be named \`__proto__\`: every object reads it as its prototype, so the binding would be dropped`,
      );
    }
    const other = byKey.get(key);
    if (other !== undefined) {
      throw new ScanError(
        `${JSON.stringify(other)} and ${JSON.stringify(entry.path)} are both the implicit model ${JSON.stringify(key)}: ` +
          `rename one (a model file's name is its path param)`,
      );
    }
    byKey.set(key, entry.path);
    out.push({ key, path: entry.path });
  }
  return out.sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
}

/**
 * `models.d.ts` for the app's model files, or nothing when the project has none (the writer removes a stale file). A
 * manifest scan failure fails the run with its diagnostic instead: returning an empty list would delete the last good
 * file and drop its `index.gen.ts` import (H14 #420 CR). Imports use the module extension a `.mts` / `.mjs` model
 * needs; the identifiers are `M0`, `M1`, ... in key order, so no model file name can make the file collide or not
 * parse.
 */
export function emitModelsFile({ projectDir, outDir }: ModelsFileOptions): GeneratedFile[] {
  let entries: ScannedEntry[];
  try {
    entries = scanModels(projectDir);
  } catch (error) {
    // A manifest scan error (one model name in both layouts) must fail the command with its diagnostic, never look
    // like "no models": the types would silently disappear until the duplicate is fixed.
    if (error instanceof ManifestScanError) throw new ScanError(error.message);
    throw error;
  }
  const models = modelKeys(entries);
  if (models.length === 0) return [];
  const from = posix.join(outDir.replace(/\\/g, "/"), "types");
  const specifier = (path: string) => {
    const relative = posix.relative(from, modelSpecifier(path.replace(/\\/g, "/")));
    return relative.startsWith(".") ? relative : `./${relative}`;
  };
  const imports = models.map((model, index) => `import type M${index} from ${quote(specifier(model.path))}`);
  const fields = models.map((model, index) => `${IDENT.test(model.key) ? model.key : quote(model.key)}: typeof M${index};`);
  const content =
    "// Generated by `sauf types:generate`. Do not edit.\n" +
    lines([
      ...imports,
      "",
      "declare module '@laratype/http' {",
      "  interface Register {",
      "    models: {",
      ...fields.map((field) => `      ${field}`),
      "    }",
      "  }",
      "}",
    ]);
  return [{ path: posix.join(from, MODELS_FILE), content }];
}
