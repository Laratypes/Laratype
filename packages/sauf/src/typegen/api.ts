import { dirname, resolve } from "node:path";
import type * as TS from "typescript";
import { lines, quote } from "./emit";
import type { GeneratedFile } from "./emit";

/**
 * The separate-repo FE output (S2 option c): one `api.ts` with a flattened `AppApi` type alias and a slim
 * manifest. Built with the TS checker only; no contract module is executed, and the output imports nothing.
 */

export interface ApiFileOptions {
  /** Project directory (absolute). */
  readonly projectDir: string;
  /** tsconfig of the project (absolute). Missing: the TS defaults plus `strict`. */
  readonly tsconfig: string | undefined;
  /** The generated `index.gen.ts` (absolute). */
  readonly indexFile: string;
  /** The `$types.d.ts` overlay root, `<out>/types` (absolute), added to `rootDirs`. */
  readonly typesDir: string;
  /** Where `api.ts` goes, relative to the project (for the result path). */
  readonly outFile: string;
}

export class ApiGenerationError extends Error {
  constructor(message: string) {
    super(`[sauf types:generate] ${message}`);
    this.name = "ApiGenerationError";
  }
}

export interface ManifestEntry {
  readonly method: string;
  readonly path: string;
  readonly errors: readonly string[];
}

const BANNER = "// Generated by `sauf types:generate`. Do not edit.\n// Self-contained: no contract library, no schema library.\n";
const ENTRY_NAME = "__laratype_api_entry.ts";
const FIELDS = ["method", "path", "params", "query", "body", "headers", "response", "status", "errors"] as const;
const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

const key = (name: string) => (IDENT.test(name) ? name : quote(name));

function compilerOptions(ts: typeof TS, options: ApiFileOptions): TS.CompilerOptions {
  let base: TS.CompilerOptions = { strict: true, target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, moduleResolution: ts.ModuleResolutionKind.Bundler };
  if (options.tsconfig) {
    const { config, error } = ts.readConfigFile(options.tsconfig, ts.sys.readFile);
    if (error) throw new ApiGenerationError(ts.flattenDiagnosticMessageText(error.messageText, "\n"));
    base = ts.parseJsonConfigFileContent(config, ts.sys, dirname(options.tsconfig)).options;
  }
  // The overlay must resolve even before the app's tsconfig lists it.
  const rootDirs = [...(base.rootDirs ?? [options.projectDir]), options.typesDir];
  return { ...base, rootDirs, noEmit: true, composite: false, incremental: false, declaration: false, skipLibCheck: true };
}

/**
 * Prints a type structurally, so the output needs no import: named types are inlined, except the TS default
 * lib ones (`Date`, `Record`, ...). A type met again while it is being printed (a cycle) prints `unknown`.
 */
function createPrinter(ts: typeof TS, program: TS.Program, checker: TS.TypeChecker, at: TS.Node) {
  const fromLib = (symbol: TS.Symbol | undefined) =>
    !!symbol?.declarations?.length && symbol.declarations.every((d) => program.isSourceFileDefaultLibrary(d.getSourceFile()));
  const inProgress = new Set<TS.Type>();
  const fallback = (type: TS.Type) =>
    checker.typeToString(type, at, ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.UseSingleQuotesForStringLiteralType | ts.TypeFormatFlags.InTypeAlias);

  const wrap = (type: TS.Type, text: string) =>
    type.flags & (ts.TypeFlags.Union | ts.TypeFlags.Intersection) || (type.getCallSignatures().length > 0 && !(type.flags & ts.TypeFlags.Union)) ? `(${text})` : text;

  const print = (type: TS.Type, indent: string): string => {
    if (type.flags & ts.TypeFlags.StringLiteral) return quote((type as TS.StringLiteralType).value);
    if (type.flags & ts.TypeFlags.NumberLiteral) return String((type as TS.NumberLiteralType).value);
    if (type.flags & ts.TypeFlags.Union) {
      const members = (type as TS.UnionType).types;
      const hasTrue = members.some((t) => t.flags & ts.TypeFlags.BooleanLiteral && fallback(t) === "true");
      const hasFalse = members.some((t) => t.flags & ts.TypeFlags.BooleanLiteral && fallback(t) === "false");
      // `T | null | undefined`, as written by hand: nullish members go last
      const nullish = ts.TypeFlags.Undefined | ts.TypeFlags.Null;
      const ordered = [...members.filter((t) => !(t.flags & nullish)), ...members.filter((t) => t.flags & nullish)];
      const parts = ordered.filter((t) => !(hasTrue && hasFalse && t.flags & ts.TypeFlags.BooleanLiteral)).map((t) => print(t, indent));
      if (hasTrue && hasFalse) parts.unshift("boolean");
      return parts.join(" | ");
    }
    if (type.flags & ts.TypeFlags.Intersection) return (type as TS.IntersectionType).types.map((t) => wrap(t, print(t, indent))).join(" & ");
    if (!(type.flags & ts.TypeFlags.Object)) return fallback(type);
    if (type.aliasSymbol && fromLib(type.aliasSymbol)) {
      const args = type.aliasTypeArguments ?? [];
      return args.length ? `${type.aliasSymbol.name}<${args.map((t) => print(t, indent)).join(", ")}>` : type.aliasSymbol.name;
    }
    if (inProgress.has(type)) return "unknown";
    inProgress.add(type);
    try {
      if (checker.isTupleType(type)) {
        const target = (type as TS.TypeReference).target as TS.TupleType;
        const items = checker.getTypeArguments(type as TS.TypeReference).map((t, i) => {
          const flags = target.elementFlags[i]!;
          if (flags & ts.ElementFlags.Variable) return `...${wrap(t, print(t, indent))}[]`;
          return `${print(t, indent)}${flags & ts.ElementFlags.Optional ? "?" : ""}`;
        });
        return `${target.readonly ? "readonly " : ""}[${items.join(", ")}]`;
      }
      if (checker.isArrayType(type)) {
        const [element] = checker.getTypeArguments(type as TS.TypeReference);
        const readonly = (type as TS.TypeReference).target.symbol?.name === "ReadonlyArray";
        return `${readonly ? "readonly " : ""}${wrap(element!, print(element!, indent))}[]`;
      }
      if (fromLib(type.symbol)) {
        const args = type.flags & ts.TypeFlags.Object && (type as TS.ObjectType).objectFlags & ts.ObjectFlags.Reference ? checker.getTypeArguments(type as TS.TypeReference) : [];
        return args.length ? `${type.symbol.name}<${args.map((t) => print(t, indent)).join(", ")}>` : type.symbol.name;
      }
      if (type.getCallSignatures().length || type.getConstructSignatures().length) return fallback(type);
      const inner = `${indent}  `;
      const lines: string[] = [];
      for (const info of checker.getIndexInfosOfType(type)) {
        lines.push(`${inner}${info.isReadonly ? "readonly " : ""}[key: ${print(info.keyType, inner)}]: ${print(info.type, inner)};`);
      }
      for (const prop of checker.getPropertiesOfType(type)) {
        const optional = prop.flags & ts.SymbolFlags.Optional ? "?" : "";
        lines.push(`${inner}${key(prop.name)}${optional}: ${print(checker.getTypeOfSymbol(prop), inner)};`);
      }
      return lines.length ? `{\n${lines.join("\n")}\n${indent}}` : "{}";
    } finally {
      inProgress.delete(type);
    }
  };
  return (type: TS.Type) => print(type, "");
}

/** Generates `api.ts` from the project's `index.gen.ts`. Throws ApiGenerationError on type errors in the program. */
export function generateApiFile(ts: typeof TS, options: ApiFileOptions): GeneratedFile & { manifest: Record<string, ManifestEntry> } {
  const entryFile = resolve(dirname(options.indexFile), ENTRY_NAME);
  const indexSpecifier = `./${options.indexFile.slice(dirname(options.indexFile).length + 1).replace(/\.ts$/, "")}`;
  // `Kind` marks each member as `ApiTypes` reads it: `true` for an endpoint, else a node's members. It is `never` when
  // `AppApi` is not a `defineApi` root, told by its brand as `isApiRoot` does at runtime.
  const entrySource = lines([
    "import type { API_ROOT, AnyEndpoint, ApiTypes } from '@laratype/contract'",
    `import type { AppApi } from '${indexSpecifier}'`,
    "export type Flat = ApiTypes<AppApi>",
    "type Kinds<A> = { [K in keyof A & string]: A[K] extends AnyEndpoint ? true : Kinds<A[K]> }",
    "export type Kind = AppApi extends { readonly [API_ROOT]: true } ? Kinds<AppApi> : never",
  ]);

  const compilerOpts = compilerOptions(ts, options);
  if (!(compilerOpts.strictNullChecks ?? compilerOpts.strict)) {
    throw new ApiGenerationError(`the contract types need strictNullChecks: set "strict": true in ${options.tsconfig ?? "the project's tsconfig"}`);
  }
  const host = ts.createCompilerHost(compilerOpts);
  const same = (a: string) => resolve(a) === entryFile;
  const { getSourceFile, fileExists, readFile } = host;
  host.getSourceFile = (fileName, languageVersion, ...rest) =>
    same(fileName) ? ts.createSourceFile(fileName, entrySource, languageVersion, true) : getSourceFile.call(host, fileName, languageVersion, ...rest);
  host.fileExists = (fileName) => same(fileName) || fileExists.call(host, fileName);
  host.readFile = (fileName) => (same(fileName) ? entrySource : readFile.call(host, fileName));

  const program = ts.createProgram([entryFile], compilerOpts, host);
  const diagnostics = ts.getPreEmitDiagnostics(program);
  if (diagnostics.length) {
    const text = ts.formatDiagnostics(diagnostics, { getCanonicalFileName: (f) => f, getCurrentDirectory: () => options.projectDir, getNewLine: () => "\n" });
    throw new ApiGenerationError(`the contract tree does not type-check:\n${text}`);
  }

  const checker = program.getTypeChecker();
  const source = program.getSourceFile(entryFile)!;
  const aliasOf = (name: string) => source.statements.find((s): s is TS.TypeAliasDeclaration => ts.isTypeAliasDeclaration(s) && s.name.text === name)!;
  const alias = aliasOf("Flat");
  const kind = checker.getTypeAtLocation(aliasOf("Kind").name);
  if (kind.flags & ts.TypeFlags.Never) throw new ApiGenerationError(`AppApi in ${options.indexFile} must be the type of the appApi from defineApi`);
  const print = createPrinter(ts, program, checker, alias);
  const propType = (type: TS.Type, name: string) => {
    const symbol = type.getProperty(name);
    return symbol ? checker.getTypeOfSymbolAtLocation(symbol, alias) : undefined;
  };
  const literal = (type: TS.Type | undefined) => (type && type.flags & ts.TypeFlags.StringLiteral ? (type as TS.StringLiteralType).value : undefined);

  const manifest: Record<string, ManifestEntry> = {};
  const walk = (type: TS.Type, kinds: TS.Type, prefix: string, indent: string): string => {
    const inner = `${indent}  `;
    const lines: string[] = [];
    for (const member of type.getProperties()) {
      const memberType = checker.getTypeOfSymbolAtLocation(member, alias);
      const memberKinds = propType(kinds, member.name)!;
      const name = prefix ? `${prefix}.${member.name}` : member.name;
      if (!(memberKinds.flags & ts.TypeFlags.BooleanLiteral)) {
        lines.push(`${inner}${key(member.name)}: ${walk(memberType, memberKinds, name, inner)};`);
        continue;
      }
      const fields = FIELDS.map((f) => {
        const text = print(propType(memberType, f)!).replace(/\n/g, `\n${inner}  `);
        return `${inner}  ${f}: ${text};`;
      });
      lines.push(`${inner}${key(member.name)}: {\n${fields.join("\n")}\n${inner}};`);
      const errors = propType(memberType, "errors")!;
      const errorTypes = errors.flags & ts.TypeFlags.Never ? [] : errors.flags & ts.TypeFlags.Union ? (errors as TS.UnionType).types : [errors];
      manifest[name] = {
        method: literal(propType(memberType, "method"))!,
        path: literal(propType(memberType, "path"))!,
        errors: [...new Set(errorTypes.map((t) => literal(propType(t, "code"))!))].sort(),
      };
    }
    return lines.length ? `{\n${lines.join("\n")}\n${indent}}` : "{}";
  };
  const appApi = walk(checker.getTypeAtLocation(alias.name), kind, "", "");

  const manifestLines = Object.entries(manifest)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([name, e]) => `  ${quote(name)}: { method: ${quote(e.method)}, path: ${quote(e.path)}, errors: [${e.errors.map(quote).join(", ")}] },`);
  const content =
    BANNER +
    lines([
      "",
      `export type AppApi = ${appApi}`,
      "",
      "/** Route name → method, full path and the error codes the endpoint can answer with. */",
      ...(manifestLines.length ? ["export const manifest = {", ...manifestLines, "} as const"] : ["export const manifest = {} as const"]),
    ]);
  return { path: options.outFile, content, manifest };
}
